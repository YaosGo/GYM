/**
 * 运动动作的中文展示名称扩展属性。
 * 优先使用 nameZh，为空或含英文时回退到术语翻译，最终回退英文 name。
 */
val Exercise.displayName: String
    get() {
        val zh = nameZh
        if (zh != null && !zh.any { it in 'a'..'z' || it in 'A'..'Z' }) return zh
        return ExerciseDisplayName.translate(name) ?: name
    }

