                remaining.deleteAt(0)
            }
            if (remaining.isEmpty()) break

            var matched = false
            // 按术语长度降序匹配
            for ((en, zh) in TERMS) {
                if (remaining.startsWith(en) &&
                    (remaining.length == en.length || remaining[en.length] in " -/,")
                ) {
                    parts.add(zh)
                    remaining.delete(0, en.length)
                    // 跳过术语后的连字符/
                    while (remaining.isNotEmpty() && remaining[0] in " -/,") {
                        remaining.deleteAt(0)
                    }
                    matched = true
                    break
                }
            }
            if (!matched) {
                // 未匹配的词：尝试全文再匹配一次，实在不行跳过
                val nextSpace = remaining.indexOfFirst { it in " -/," }
                val word = if (nextSpace == -1) remaining.toString()
                else remaining.substring(0, nextSpace)
                // 尝试单数形式匹配常见词
                val singular = word.trimEnd('s')
                val found = TERMS[singular] ?: TERMS[word]
                if (found != null) {
                    parts.add(found)
                }
                if (nextSpace == -1) break
                remaining.delete(0, nextSpace + 1)
            }
        }

        return if (parts.isNotEmpty()) parts.joinToString("") else null
    }
}
